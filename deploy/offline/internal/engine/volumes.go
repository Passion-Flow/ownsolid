const UtilityDestination = "/var/lib/projectone/volume-init"
const UtilityPrivateDirectory = "private"
const utilityEntrypoint = "/projectone-never-started-initializer"
const neverStarted = "0001-01-01T00:00:00Z"
const nanosecondsPerMillicore = 1000000

var objectIdentity = regexp.MustCompile(`^[a-f0-9]{32}$`)
var containerIdentity = regexp.MustCompile(`^[a-f0-9]{64}$`)
var objectRole = regexp.MustCompile(`^[a-z][a-z0-9_-]{0,62}$`)

// Ownership is generated by the scope caller and must have a durable intent before mutation.
type Ownership struct {
	ScopeID     string `json:"scope_id"`
	OperationID string `json:"operation_id"`
	Role        string `json:"role"`
}

func (o Ownership) valid() bool {
	return objectIdentity.MatchString(o.ScopeID) && objectIdentity.MatchString(o.OperationID) && objectRole.MatchString(o.Role)
}
func (o Ownership) VolumeName() string  { return "projectone-" + o.ScopeID + "-" + o.Role }
func (o Ownership) utilityName() string { return o.VolumeName() + "-init-" + o.OperationID }
func (o Ownership) labels() map[string]string {
	return map[string]string{"io.projectone.isolated-scope": o.ScopeID, "io.projectone.operation": o.OperationID, "io.projectone.purpose": "isolated-validation", "io.projectone.role": o.Role}
}
func (o Ownership) matches(labels map[string]string) bool {
	for key, value := range o.labels() {
		if labels[key] != value {
			return false
		}
	}
	return true
}

type Volume struct {
	Name    string
	Driver  string
	Scope   string
	Labels  map[string]string
	Options map[string]string
}
type Utility struct {
	ID     string `json:"Id"`
	Name   string
	Image  string
	Config struct {
		Image      string
		User       string
		Entrypoint []string
		Labels     map[string]string
	}
	State struct {
		Status     string
		Running    bool
		Restarting bool
		Dead       bool
		PID        int `json:"Pid"`
		StartedAt  string
	}
	Mounts []struct {
		Type        string
		Name        string
		Destination string
		Driver      string
		RW          bool
	}
	HostConfig struct {
		NetworkMode    string
		ReadonlyRootfs bool
		Privileged     bool
		Memory         int64
		NanoCPUs       int64 `json:"NanoCpus"`
		PIDs           int64 `json:"PidsLimit"`
		CapDrop        []string
		CapAdd         []string
		SecurityOpt    []string
		Binds          []string
		VolumesFrom    []string
		AutoRemove     bool
		Devices        []json.RawMessage
		DeviceRequests []json.RawMessage
		PortBindings   map[string]json.RawMessage
		RestartPolicy  struct{ Name string }
		Mounts         []struct {
			Type          string
			Source        string
			Target        string
			ReadOnly      bool
			VolumeOptions *struct {
				NoCopy  bool
				Subpath string
			}
		}
	}
}

func (c *Client) utilityPolicy() error {
	if c.config.Utility == nil {
		return failure("OFFLINE_ENGINE_UTILITY_CONFIGURATION_REQUIRED")
	}
	return nil
}
func (c *Client) jsonRequest(ctx context.Context, method, path string, query url.Values, body any) ([]byte, int, error) {
	raw, e := json.Marshal(body)
	if e != nil {
		return nil, 0, failure("OFFLINE_ENGINE_JSON_REQUEST_INVALID")
	}
	return c.requestContentType(ctx, method, path, query, bytes.NewReader(raw), c.config.RequestSeconds, "application/json")
}
func (c *Client) InspectVolume(ctx context.Context, o Ownership) (Volume, bool, error) {
	result := Volume{}
	if !o.valid() {
		return result, false, failure("OFFLINE_ENGINE_VOLUME_CONTEXT_INVALID")
	}
	raw, status, e := c.request(ctx, http.MethodGet, "/v"+c.policy.APIVersion+"/volumes/"+url.PathEscape(o.VolumeName()), nil, nil, c.config.RequestSeconds)
	if e != nil {
		return result, false, e
	}
	if status == http.StatusNotFound {
		return result, false, nil
	}
	if status != http.StatusOK || wire.UniqueJSON(raw, &result) != nil || result.Name != o.VolumeName() || result.Driver != "local" || result.Scope != "local" || len(result.Options) > 0 || !o.matches(result.Labels) {
		return Volume{}, false, failure("OFFLINE_ENGINE_VOLUME_OWNER_OR_DRIVER_MISMATCH")
	}
	return result, true, nil
}
func (c *Client) CreateVolume(ctx context.Context, o Ownership) (Volume, error) {
	if e := c.utilityPolicy(); e != nil {
		return Volume{}, e
	}
	if _, found, e := c.InspectVolume(ctx, o); e != nil {
		return Volume{}, e
	} else if found {
		return Volume{}, failure("OFFLINE_ENGINE_EXISTING_VOLUME_PRESERVED")
	}
	raw, status, e := c.jsonRequest(ctx, http.MethodPost, "/v"+c.policy.APIVersion+"/volumes/create", nil, map[string]any{"Name": o.VolumeName(), "Driver": "local", "Labels": o.labels()})
	if e != nil {
		return Volume{}, failure("OFFLINE_ENGINE_VOLUME_CREATE_UNCERTAIN")
	}
	var result Volume
	if status != http.StatusCreated || wire.UniqueJSON(raw, &result) != nil || result.Name != o.VolumeName() || result.Driver != "local" || result.Scope != "local" || len(result.Options) > 0 || !o.matches(result.Labels) {
		return Volume{}, failure("OFFLINE_ENGINE_VOLUME_CREATE_UNCERTAIN")
	}
	observed, found, e := c.InspectVolume(ctx, o)
	if e != nil || !found {
		return result, failure("OFFLINE_ENGINE_VOLUME_CREATE_UNCERTAIN")
	}
	return observed, nil
}
func utilityIdentity(o Ownership, image string, uid, gid int) bool {
	return o.valid() && uid > 0 && gid > 0 && uid <= math.MaxInt32 && gid <= math.MaxInt32 && len(image) == len("sha256:")+64 && image[:len("sha256:")] == "sha256:" && wire.ValidSHA256(image[len("sha256:"):])
}
func (c *Client) InspectUtility(ctx context.Context, o Ownership, image string, uid, gid int) (Utility, bool, error) {
	result := Utility{}
	if e := c.utilityPolicy(); e != nil {
		return result, false, e
	}
	if !utilityIdentity(o, image, uid, gid) {
		return result, false, failure("OFFLINE_ENGINE_UTILITY_CONTEXT_INVALID")
	}
	raw, status, e := c.request(ctx, http.MethodGet, "/v"+c.policy.APIVersion+"/containers/"+url.PathEscape(o.utilityName())+"/json", nil, nil, c.config.RequestSeconds)
	if e != nil {
		return result, false, e
	}
	if status == http.StatusNotFound {
		return result, false, nil
	}
	if status != http.StatusOK || wire.UniqueJSON(raw, &result) != nil {
		return result, false, failure("OFFLINE_ENGINE_UTILITY_RESPONSE_INVALID")
	}
	u := c.config.Utility
	h := result.HostConfig
	if !containerIdentity.MatchString(result.ID) || result.Name != "/"+o.utilityName() || result.Image != image || result.Config.Image != image || result.Config.User != strconv.Itoa(uid)+":"+strconv.Itoa(gid) || !slices.Equal(result.Config.Entrypoint, []string{utilityEntrypoint}) || !o.matches(result.Config.Labels) || result.State.Status != "created" || result.State.PID != 0 || result.State.Running || result.State.Restarting || result.State.Dead || result.State.StartedAt != neverStarted || len(result.Mounts) != 1 || h.NetworkMode != "none" || !h.ReadonlyRootfs || h.Privileged || h.Memory != u.MemoryBytes || h.NanoCPUs != u.MilliCPU*nanosecondsPerMillicore || h.PIDs != u.PIDs || !slices.Equal(h.CapDrop, []string{"ALL"}) || len(h.CapAdd) > 0 || !slices.Equal(h.SecurityOpt, []string{"no-new-privileges:true"}) || len(h.Binds) > 0 || len(h.VolumesFrom) > 0 || len(h.Devices) > 0 || len(h.DeviceRequests) > 0 || len(h.PortBindings) > 0 || h.AutoRemove || h.RestartPolicy.Name != "no" || len(h.Mounts) != 1 {
		return Utility{}, false, failure("OFFLINE_ENGINE_NEVER_STARTED_UTILITY_REQUIRED")
	}
	mount := result.Mounts[0]
	requested := h.Mounts[0]
	if mount.Type != "volume" || mount.Name != o.VolumeName() || mount.Destination != UtilityDestination || mount.Driver != "local" || !mount.RW || requested.Type != "volume" || requested.Source != o.VolumeName() || requested.Target != UtilityDestination || requested.ReadOnly || requested.VolumeOptions == nil || !requested.VolumeOptions.NoCopy || requested.VolumeOptions.Subpath != "" {
		return Utility{}, false, failure("OFFLINE_ENGINE_UTILITY_MOUNT_MISMATCH")
	}
	return result, true, nil
}
func (c *Client) CreateUtility(ctx context.Context, o Ownership, image string, uid, gid int) (Utility, error) {
	if !utilityIdentity(o, image, uid, gid) {
		return Utility{}, failure("OFFLINE_ENGINE_UTILITY_CONTEXT_INVALID")
	}
	if _, found, e := c.InspectUtility(ctx, o, image, uid, gid); e != nil {
		return Utility{}, e
	} else if found {
		return Utility{}, failure("OFFLINE_ENGINE_EXISTING_UTILITY_PRESERVED")
	}
	if _, found, e := c.InspectVolume(ctx, o); e != nil {
		return Utility{}, e
	} else if !found {
		return Utility{}, failure("OFFLINE_ENGINE_OWNED_VOLUME_REQUIRED")
	}
	value, found, e := c.Inspect(ctx, image)
	if e != nil {
		return Utility{}, e
	}
	if !found || value.Config == nil || len(value.Config.Volumes) > 0 {
		return Utility{}, failure("OFFLINE_ENGINE_UTILITY_IMAGE_WITHOUT_IMPLICIT_VOLUMES_REQUIRED")
	}
	if e = c.noForeignConsumers(ctx, o, ""); e != nil {
		return Utility{}, e
	}
	u := c.config.Utility
	body := map[string]any{"Image": image, "User": strconv.Itoa(uid) + ":" + strconv.Itoa(gid), "Entrypoint": []string{utilityEntrypoint}, "Cmd": []string{}, "WorkingDir": "/", "Labels": o.labels(), "HostConfig": map[string]any{"NetworkMode": "none", "ReadonlyRootfs": true, "Privileged": false, "AutoRemove": false, "RestartPolicy": map[string]string{"Name": "no"}, "CapDrop": []string{"ALL"}, "SecurityOpt": []string{"no-new-privileges:true"}, "Memory": u.MemoryBytes, "NanoCpus": u.MilliCPU * nanosecondsPerMillicore, "PidsLimit": u.PIDs, "Mounts": []any{map[string]any{"Type": "volume", "Source": o.VolumeName(), "Target": UtilityDestination, "ReadOnly": false, "VolumeOptions": map[string]bool{"NoCopy": true}}}}}
	raw, status, e := c.jsonRequest(ctx, http.MethodPost, "/v"+c.policy.APIVersion+"/containers/create", url.Values{"name": {o.utilityName()}, "platform": {"linux/amd64"}}, body)
	if e != nil {
		return Utility{}, failure("OFFLINE_ENGINE_UTILITY_CREATE_UNCERTAIN")
	}
	var reply struct {
		ID       string `json:"Id"`
		Warnings []string
	}
	if status != http.StatusCreated || wire.UniqueJSON(raw, &reply) != nil || !containerIdentity.MatchString(reply.ID) || len(reply.Warnings) > 0 {
		return Utility{}, failure("OFFLINE_ENGINE_UTILITY_CREATE_UNCERTAIN")
	}
	observed, found, e := c.InspectUtility(ctx, o, image, uid, gid)
	if e != nil || !found || observed.ID != reply.ID {
		return Utility{ID: reply.ID}, failure("OFFLINE_ENGINE_UTILITY_CREATE_UNCERTAIN")
	}
	return observed, nil
}
func (c *Client) noForeignConsumers(ctx context.Context, o Ownership, utilityID string) error {
	filters, _ := json.Marshal(map[string][]string{"volume": {o.VolumeName()}})
	raw, status, e := c.request(ctx, http.MethodGet, "/v"+c.policy.APIVersion+"/containers/json", url.Values{"all": {"1"}, "filters": {string(filters)}}, nil, c.config.RequestSeconds)
	if e != nil {
		return e
	}
	var consumers []struct {
		ID string `json:"Id"`
	}
	if status != http.StatusOK || wire.UniqueJSON(raw, &consumers) != nil {
		return failure("OFFLINE_ENGINE_VOLUME_CONSUMER_INSPECTION_FAILED")
	}
	for _, value := range consumers {
		if utilityID == "" || value.ID != utilityID {
			return failure("OFFLINE_ENGINE_FOREIGN_VOLUME_CONSUMER_PRESERVED")
		}
	}
	return nil
}
func (c *Client) RemoveUtility(ctx context.Context, o Ownership, image string, uid, gid int) error {
	value, found, e := c.InspectUtility(ctx, o, image, uid, gid)
	if e != nil {
		return e
	}
	if !found {
		return failure("OFFLINE_ENGINE_OWNED_UTILITY_REQUIRED")
	}
	_, status, e := c.request(ctx, http.MethodDelete, "/v"+c.policy.APIVersion+"/containers/"+value.ID, url.Values{"force": {"0"}, "v": {"0"}}, nil, c.config.RequestSeconds)
	if e != nil || status != http.StatusNoContent {
		return failure("OFFLINE_ENGINE_UTILITY_REMOVAL_UNCERTAIN")
	}
	if _, found, e = c.InspectUtility(ctx, o, image, uid, gid); e != nil || found {
		return failure("OFFLINE_ENGINE_UTILITY_REMOVAL_UNCERTAIN")
	}
	return nil
}
