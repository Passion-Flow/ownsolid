source=root/'v1/models/openapi.json'
generator=Path('/root/lane-rel-workspace-operations/tools/codegen/sdk/generate.py')
spec=importlib.util.spec_from_file_location('prototype_codegen',generator)
module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module)
