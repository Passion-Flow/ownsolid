func preparationArtifactEnvironment(key string) bool {
	switch key {
	case "PROJECT_ONE_MODEL_PREPARATION_ARTIFACT_ROOT":
		return true
	case "PROJECT_ONE_MODEL_PREPARATION_IMAGE_REFERENCE":
		return true
	case "PROJECT_ONE_MODEL_PREPARATION_IMAGE_ID":
		return true
	case "PROJECT_ONE_MODEL_PREPARATION_WORKER_SOURCE_SHA256":
		return true
	}
	return false
}
