// PublicErrorCode reduces failures to the existing canonical public registry.
// Private SQL, filesystem and provider diagnostics never become run/audit text.
func PublicErrorCode(e error) string { code, _ := publicProblem(e); return code }
func publicProblem(e error) (string, int) {
	if e == nil {
		return "STORAGE_UNAVAILABLE", 503
	}
	code := e.Error()
	if status, ok := privateClusterProblemStatus(code); ok {
		return code, status
	}
	if status, ok := problemStatuses[code]; ok {
		return code, status
	}
	if status, ok := registryProblemStatus(code); ok {
		return code, status
	}
	if status, ok := taskDeliveryProblemStatus(code); ok {
		return code, status
	}
	if code != "" && wire.KnownInferenceError(code) {
		return code, 409
	}
	return "STORAGE_UNAVAILABLE", 503
}

// Problem retains the owned default policy for standalone consumers.
func Problem(w http.ResponseWriter, requestID string, e error) {
	ProblemWithPolicy(w, requestID, e, config.DefaultHTTPPolicy())
}

// ProblemWithPolicy takes the serving owner's typed policy, never ambient input.
func ProblemWithPolicy(w http.ResponseWriter, requestID string, e error, policy config.HTTPPolicy) {
	code, status := publicProblem(e)
	if policy.Validate() != nil {
		policy = config.DefaultHTTPPolicy()
		code, status = "SERVICE_NOT_READY", http.StatusServiceUnavailable
	}
	w.Header().Del("Retry-After")
	if status == http.StatusTooManyRequests {
		retry := policy.RateLimitFallbackRetrySeconds
		var rate interface{ RetrySeconds() int }
		if errors.As(e, &rate) && rate.RetrySeconds() > 0 {
			retry = rate.RetrySeconds()
		}
		w.Header().Set("Retry-After", strconv.Itoa(retry))
	}
	if status == http.StatusServiceUnavailable {
		w.Header().Set("Retry-After", strconv.Itoa(policy.ServiceUnavailableRetrySeconds))
	}
	w.Header().Set("Content-Type", "application/problem+json")
	w.WriteHeader(status)
	_ = json.NewEncoder(w).Encode(map[string]any{"type": "about:blank", "title": code, "status": status, "code": code, "request_id": requestID})
}
