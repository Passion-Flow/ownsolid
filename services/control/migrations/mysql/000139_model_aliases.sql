CREATE TABLE model_aliases (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    node_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    gateway_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    name VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(name,'^[a-z][a-z0-9.-]{0,63}$','c')),
    deployment_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    deployment_revision BIGINT NOT NULL CHECK(deployment_revision BETWEEN 1 AND 9007199254740991),
    revision BIGINT NOT NULL DEFAULT 1 CHECK(revision BETWEEN 1 AND 9007199254740991),
    created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    idempotency_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    fingerprint VARBINARY(32) NOT NULL CHECK(OCTET_LENGTH(fingerprint)=32),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    disabled_at DATETIME(6),
    UNIQUE(tenant_id,workspace_id,id),
    UNIQUE(tenant_id,workspace_id,name),
    UNIQUE(tenant_id,workspace_id,created_by,idempotency_key),
    FOREIGN KEY(tenant_id,workspace_id,node_id,gateway_id) REFERENCES gateway_instances(tenant_id,workspace_id,node_id,id),
    FOREIGN KEY(tenant_id,workspace_id,node_id,deployment_id) REFERENCES deployments(tenant_id,workspace_id,node_id,id),
    FOREIGN KEY(created_by) REFERENCES users(id),
    CONSTRAINT model_aliases_id_canonical CHECK(id IS NULL OR REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_aliases_tenant_id_canonical CHECK(tenant_id IS NULL OR REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_aliases_workspace_id_canonical CHECK(workspace_id IS NULL OR REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_aliases_node_id_canonical CHECK(node_id IS NULL OR REGEXP_LIKE(node_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_aliases_gateway_id_canonical CHECK(gateway_id IS NULL OR REGEXP_LIKE(gateway_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_aliases_deployment_id_canonical CHECK(deployment_id IS NULL OR REGEXP_LIKE(deployment_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_aliases_created_by_canonical CHECK(created_by IS NULL OR REGEXP_LIKE(created_by,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_aliases_idempotency_key_canonical CHECK(idempotency_key IS NULL OR REGEXP_LIKE(idempotency_key,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
