CREATE TABLE training_attempts (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    node_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    task_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    attempt_number integer NOT NULL CHECK(attempt_number BETWEEN 1 AND 1000),
    state VARCHAR(24) NOT NULL CHECK(state IN ('pending','preparing','running','stopping','succeeded','cancelled','failed','recovery_required','stopped')),
    requested_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    requested_audience VARCHAR(8) NOT NULL CHECK(requested_audience IN ('portal','admin')),
    requested_epoch bigint NOT NULL CHECK(requested_epoch>=0),
    membership_authority CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    input_inventory JSON NOT NULL CHECK(JSON_TYPE(input_inventory)='OBJECT' AND OCTET_LENGTH(CAST(input_inventory AS CHAR CHARACTER SET utf8mb4))<=65536),
    resume_checkpoint_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    last_event_sequence bigint NOT NULL DEFAULT 0 CHECK(last_event_sequence BETWEEN 0 AND 1000000),
    last_global_step integer NOT NULL DEFAULT 0 CHECK(last_global_step BETWEEN 0 AND 1000),
    stop_token_hash VARBINARY(32) CHECK(stop_token_hash IS NULL OR OCTET_LENGTH(stop_token_hash)=32),
    outcome_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin CHECK(outcome_sha256 IS NULL OR REGEXP_LIKE(outcome_sha256,'^[a-f0-9]{64}$','c')),
    outcome JSON CHECK(outcome IS NULL OR JSON_TYPE(outcome)='OBJECT' AND OCTET_LENGTH(CAST(outcome AS CHAR CHARACTER SET utf8mb4))<=16777216),
    physical_stop_receipt JSON CHECK(physical_stop_receipt IS NULL OR JSON_TYPE(physical_stop_receipt)='OBJECT' AND OCTET_LENGTH(CAST(physical_stop_receipt AS CHAR CHARACTER SET utf8mb4))<=32768),
    physical_stop_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin CHECK(physical_stop_sha256 IS NULL OR REGEXP_LIKE(physical_stop_sha256,'^[a-f0-9]{64}$','c')),
    physical_stopped_at DATETIME(6),
    error_code VARCHAR(80),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    started_at DATETIME(6),
    finished_at DATETIME(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UNIQUE(tenant_id,workspace_id,job_id,id),
    UNIQUE(job_id,attempt_number),
    UNIQUE(task_id),
    FOREIGN KEY(tenant_id,workspace_id,job_id) REFERENCES training_jobs(tenant_id,workspace_id,id),
    FOREIGN KEY(tenant_id,workspace_id,node_id) REFERENCES managed_nodes(tenant_id,workspace_id,id),
    FOREIGN KEY(tenant_id,workspace_id,node_id,task_id) REFERENCES node_tasks(tenant_id,workspace_id,node_id,id),
    CHECK(requested_audience='admin' OR membership_authority IS NOT NULL),
    CHECK((physical_stop_receipt IS NULL)=(physical_stop_sha256 IS NULL)),
    CHECK((physical_stop_receipt IS NULL)=(physical_stopped_at IS NULL)),
    CHECK((outcome IS NULL)=(outcome_sha256 IS NULL)),
    uncleared_job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin GENERATED ALWAYS AS(CASE WHEN state IN('pending','preparing','running','stopping','recovery_required') AND physical_stopped_at IS NULL THEN job_id ELSE NULL END) STORED,
    UNIQUE KEY training_attempt_one_uncleared_job_idx(uncleared_job_id),
    KEY training_attempt_scope_page_idx(tenant_id,workspace_id,job_id,created_at DESC,id DESC),
    FOREIGN KEY(requested_by) REFERENCES users(id),
    CONSTRAINT training_attempts_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_attempts_tenant_id_canonical CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_attempts_workspace_id_canonical CHECK(REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_attempts_job_id_canonical CHECK(REGEXP_LIKE(job_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_attempts_node_id_canonical CHECK(REGEXP_LIKE(node_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_attempts_task_id_canonical CHECK(task_id IS NULL OR REGEXP_LIKE(task_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_attempts_requested_by_canonical CHECK(REGEXP_LIKE(requested_by,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_attempts_membership_authority_canonical CHECK(membership_authority IS NULL OR REGEXP_LIKE(membership_authority,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_attempts_resume_checkpoint_id_canonical CHECK(resume_checkpoint_id IS NULL OR REGEXP_LIKE(resume_checkpoint_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
