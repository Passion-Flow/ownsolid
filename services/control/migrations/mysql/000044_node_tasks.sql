CREATE TABLE node_tasks (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    node_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    operation VARCHAR(64) NOT NULL CHECK(operation IN('collect_facts.v1','node_exporter.install.v1','node_exporter.start.v1','node_exporter.stop.v1','node_exporter.remove.v1','node_exporter.observe.v1','node_exporter.configure.v1','node_exporter.restart.v1','node_exporter.upgrade.v1','node_exporter.rollback.v1','node_exporter.logs.v1','inference.deploy.v1','inference.stop.v1','inference.remove.v1','inference.observe.v1','inference.verify.v1','training.run.v1','model.prepare.v1','inference.derived.v1')),
    state VARCHAR(16) NOT NULL CHECK(state IN('pending','running','succeeded','failed','cancelled')),
    idempotency_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    requested_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    attempt INT NOT NULL DEFAULT 0 CHECK(attempt BETWEEN 0 AND 3),
    lease_token_hash VARBINARY(32) CHECK(lease_token_hash IS NULL OR OCTET_LENGTH(lease_token_hash)=32),
    lease_expires_at DATETIME(6),
    error_code VARCHAR(64),
    completed_lease_hash VARBINARY(32) CHECK(completed_lease_hash IS NULL OR OCTET_LENGTH(completed_lease_hash)=32),
    result_hash VARBINARY(32) CHECK(result_hash IS NULL OR OCTET_LENGTH(result_hash)=32),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    deadline_at DATETIME(6) NOT NULL,
    completed_at DATETIME(6),
    payload JSON NOT NULL DEFAULT (JSON_OBJECT()) CHECK(JSON_TYPE(payload)='OBJECT' AND OCTET_LENGTH(CAST(payload AS CHAR CHARACTER SET utf8mb4))<=32768),
    request_fingerprint VARBINARY(32) CHECK(request_fingerprint IS NULL OR OCTET_LENGTH(request_fingerprint)=32),
    inference_requested_epoch BIGINT,
    inflight_node_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin GENERATED ALWAYS AS(CASE WHEN state IN('pending','running') THEN node_id ELSE NULL END) STORED,
    UNIQUE KEY tasks_idempotency_identity(node_id,idempotency_key),
    UNIQUE KEY tasks_scope_identity(tenant_id,workspace_id,node_id,id),
    UNIQUE KEY tasks_one_inflight_idx(inflight_node_id),
    KEY tasks_scope_list_idx(tenant_id,workspace_id,node_id,created_at DESC,id DESC),
    KEY tasks_claim_idx(node_id,state,created_at),
    FOREIGN KEY(requested_by) REFERENCES users(id),
    FOREIGN KEY(tenant_id,workspace_id,node_id) REFERENCES managed_nodes(tenant_id,workspace_id,id),
    CHECK((state='running')=(lease_token_hash IS NOT NULL AND lease_expires_at IS NOT NULL)),
    CHECK((state IN('succeeded','failed','cancelled'))=(completed_at IS NOT NULL)),
    CONSTRAINT node_derived_delegation_presence CHECK((operation='inference.derived.v1' AND inference_requested_epoch IS NOT NULL AND inference_requested_epoch>=1) OR(operation<>'inference.derived.v1' AND inference_requested_epoch IS NULL)),
    CONSTRAINT node_tasks_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT node_tasks_idempotency_canonical CHECK(REGEXP_LIKE(idempotency_key,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
