CREATE TABLE knowledge_chunks (
 tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 base_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 document_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 generation_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 source_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 attempt_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 ordinal INTEGER NOT NULL CHECK(ordinal BETWEEN 0 AND 4095),
 start_byte INTEGER NOT NULL CHECK(start_byte BETWEEN 0 AND 2097151),
 end_byte INTEGER NOT NULL,
 token_count INTEGER NOT NULL CHECK(token_count BETWEEN 1 AND 254),
 embedding JSON NOT NULL CHECK(JSON_TYPE(embedding)='ARRAY' AND JSON_LENGTH(embedding)=384 AND OCTET_LENGTH(CAST(embedding AS CHAR CHARACTER SET utf8mb4))<=32768),
 PRIMARY KEY(attempt_id,ordinal),
 KEY knowledge_scoped_exact_search_idx(tenant_id,workspace_id,base_id,generation_id,document_id,source_id),
 FOREIGN KEY(tenant_id,workspace_id,base_id,document_id,generation_id,source_id,attempt_id) REFERENCES knowledge_attempts(tenant_id,workspace_id,base_id,document_id,generation_id,source_id,id),
 CONSTRAINT knowledge_chunks_tenant_id_canonical CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_chunks_workspace_id_canonical CHECK(REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_chunks_base_id_canonical CHECK(REGEXP_LIKE(base_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_chunks_document_id_canonical CHECK(REGEXP_LIKE(document_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_chunks_generation_id_canonical CHECK(REGEXP_LIKE(generation_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_chunks_source_id_canonical CHECK(REGEXP_LIKE(source_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_chunks_attempt_id_canonical CHECK(REGEXP_LIKE(attempt_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_chunk_byte_range CHECK(end_byte>start_byte AND end_byte<=2097152 AND end_byte-start_byte<=65536)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
