CREATE TABLE dataset_versions (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    dataset_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    draft_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    attempt_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    ordinal BIGINT NOT NULL CHECK(ordinal BETWEEN 1 AND 9007199254740991),
    parent_version_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    published_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    published_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    raw_source_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(raw_source_sha256,'^[a-f0-9]{64}$','c')),
    effective_source_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(effective_source_sha256,'^[a-f0-9]{64}$','c')),
    manifest_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(manifest_sha256,'^[a-f0-9]{64}$','c')),
    manifest JSON NOT NULL,
    row_mapping_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(row_mapping_sha256,'^[a-f0-9]{64}$','c')),
    retired_at DATETIME(6),
    retire_reason VARCHAR(500),
    UNIQUE KEY dataset_version_scope_identity(tenant_id,workspace_id,dataset_id,id),
    UNIQUE KEY dataset_version_draft_identity(tenant_id,workspace_id,dataset_id,draft_id,id),
    UNIQUE KEY dataset_version_ordinal(dataset_id,ordinal),
    UNIQUE KEY dataset_version_job(job_id),
    KEY dataset_version_page_idx(tenant_id,workspace_id,dataset_id,published_at DESC,id DESC),
    FOREIGN KEY(tenant_id,workspace_id,dataset_id,draft_id,job_id) REFERENCES dataset_jobs(tenant_id,workspace_id,dataset_id,draft_id,id),
    FOREIGN KEY(tenant_id,workspace_id,job_id,attempt_id) REFERENCES dataset_job_attempts(tenant_id,workspace_id,job_id,id),
    FOREIGN KEY(tenant_id,workspace_id,dataset_id,parent_version_id) REFERENCES dataset_versions(tenant_id,workspace_id,dataset_id,id),
    FOREIGN KEY(published_by) REFERENCES users(id),
    CHECK(JSON_TYPE(manifest)='OBJECT' AND OCTET_LENGTH(CAST(manifest AS CHAR CHARACTER SET utf8mb4))<=8388608),
    CHECK((retired_at IS NULL AND retire_reason IS NULL) OR (retired_at IS NOT NULL AND retire_reason IS NOT NULL AND CHAR_LENGTH(retire_reason)>0)),
    CONSTRAINT dataset_versions_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_versions_tenant_id_canonical CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_versions_workspace_id_canonical CHECK(REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_versions_dataset_id_canonical CHECK(REGEXP_LIKE(dataset_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_versions_draft_id_canonical CHECK(REGEXP_LIKE(draft_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_versions_job_id_canonical CHECK(REGEXP_LIKE(job_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_versions_attempt_id_canonical CHECK(REGEXP_LIKE(attempt_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_versions_parent_version_id_canonical CHECK(parent_version_id IS NULL OR REGEXP_LIKE(parent_version_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_versions_published_by_canonical CHECK(REGEXP_LIKE(published_by,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
