CREATE TABLE invitations (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    email_canonical VARCHAR(254) NOT NULL,
    locale VARCHAR(16) NOT NULL CHECK(locale IN('en','zh-CN')),
    role VARCHAR(16) NOT NULL DEFAULT 'member' CHECK(role='member'),
    status VARCHAR(16) NOT NULL CHECK(status IN('pending','accepted','revoked','expired')),
    token_hash VARBINARY(32) UNIQUE CHECK(token_hash IS NULL OR OCTET_LENGTH(token_hash)=32),
    token_generation INT NOT NULL DEFAULT 1 CHECK(token_generation>=1),
    version BIGINT NOT NULL DEFAULT 1 CHECK(version BETWEEN 1 AND 9007199254740991),
    created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    accepted_user_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    expires_at DATETIME(6) NOT NULL,
    accepted_at DATETIME(6),
    revoked_at DATETIME(6),
    pending_email VARCHAR(254) GENERATED ALWAYS AS(CASE WHEN status='pending' THEN email_canonical ELSE NULL END) STORED,
    UNIQUE KEY invitations_pending_email_idx(pending_email),
    KEY invitations_list_idx(created_at DESC,id DESC),
    FOREIGN KEY(created_by) REFERENCES users(id),
    FOREIGN KEY(accepted_user_id) REFERENCES users(id),
    FOREIGN KEY(tenant_id,workspace_id) REFERENCES workspaces(tenant_id,id),
    CHECK(email_canonical=LOWER(email_canonical)),
    CHECK(expires_at>created_at),
    CHECK((status='pending')=(token_hash IS NOT NULL)),
    CHECK((status='accepted' AND accepted_user_id IS NOT NULL AND accepted_at IS NOT NULL) OR(status<>'accepted' AND accepted_user_id IS NULL AND accepted_at IS NULL)),
    CHECK((status='revoked')=(revoked_at IS NOT NULL)),
    CONSTRAINT invitations_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
