CREATE TABLE dataset_rows (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    dataset_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    draft_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    line_number INT NOT NULL CHECK(line_number BETWEEN 1 AND 10000),
    revision BIGINT NOT NULL DEFAULT 1 CHECK(revision BETWEEN 1 AND 9007199254740991),
    source_id TEXT CHECK(source_id IS NULL OR OCTET_LENGTH(source_id) BETWEEN 1 AND 512),
    prompt TEXT CHECK(prompt IS NULL OR OCTET_LENGTH(prompt) BETWEEN 1 AND 32768),
    completion TEXT CHECK(completion IS NULL OR OCTET_LENGTH(completion) BETWEEN 1 AND 32768),
    error_code VARCHAR(80),
    raw_preview TEXT NOT NULL DEFAULT ('') CHECK(OCTET_LENGTH(raw_preview)<=4096),
    preview_replaced BOOLEAN NOT NULL DEFAULT 0 CHECK(preview_replaced IN(0,1)),
    deleted BOOLEAN NOT NULL DEFAULT 0 CHECK(deleted IN(0,1)),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UNIQUE KEY dataset_row_scope_identity(tenant_id,workspace_id,dataset_id,draft_id,id),
    UNIQUE KEY dataset_row_line_identity(draft_id,line_number),
    KEY dataset_row_page_idx(tenant_id,workspace_id,draft_id,deleted,line_number,id),
    FOREIGN KEY(tenant_id,workspace_id,dataset_id,draft_id) REFERENCES dataset_drafts(tenant_id,workspace_id,dataset_id,id),
    CHECK((error_code IS NULL AND source_id IS NOT NULL AND prompt IS NOT NULL AND completion IS NOT NULL) OR (error_code IS NOT NULL AND source_id IS NULL AND prompt IS NULL AND completion IS NULL)),
    CONSTRAINT dataset_rows_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_rows_tenant_id_canonical CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_rows_workspace_id_canonical CHECK(REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_rows_dataset_id_canonical CHECK(REGEXP_LIKE(dataset_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_rows_draft_id_canonical CHECK(REGEXP_LIKE(draft_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
