CREATE TABLE dataset_drafts (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    dataset_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    requested_audience VARCHAR(8) NOT NULL CHECK(requested_audience IN('portal','admin')),
    requested_epoch BIGINT NOT NULL CHECK(requested_epoch>=0),
    membership_authority CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    parent_version_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    source_object_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    source_name VARCHAR(255) NOT NULL CHECK(CHAR_LENGTH(source_name)>0),
    source_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(source_sha256,'^[a-f0-9]{64}$','c')),
    expected_bytes BIGINT NOT NULL CHECK(expected_bytes BETWEEN 1 AND 67108864),
    source_received_at DATETIME(6),
    upload_attempt_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    upload_expires_at DATETIME(6),
    state VARCHAR(16) NOT NULL CHECK(state IN('uploading','validating','editing','publishing','published','failed','cancelled')),
    revision BIGINT NOT NULL DEFAULT 1 CHECK(revision BETWEEN 1 AND 9007199254740991),
    total_rows INT NOT NULL DEFAULT 0 CHECK(total_rows BETWEEN 0 AND 10000),
    invalid_rows INT NOT NULL DEFAULT 0 CHECK(invalid_rows BETWEEN 0 AND 10001),
    validation_completed_at DATETIME(6),
    fatal_source_error BOOLEAN NOT NULL DEFAULT 0 CHECK(fatal_source_error IN(0,1)),
    validation_errors JSON NOT NULL DEFAULT (JSON_ARRAY()),
    errors_truncated BOOLEAN NOT NULL DEFAULT 0 CHECK(errors_truncated IN(0,1)),
    error_code VARCHAR(80),
    error_line_number INT CHECK(error_line_number BETWEEN 0 AND 10001),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    creation_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    creation_fingerprint VARBINARY(32) NOT NULL CHECK(OCTET_LENGTH(creation_fingerprint)=32),
    UNIQUE KEY dataset_draft_full_identity(tenant_id,workspace_id,dataset_id,id),
    UNIQUE KEY dataset_draft_scope_identity(tenant_id,workspace_id,id),
    UNIQUE KEY dataset_draft_creation_intent(tenant_id,workspace_id,dataset_id,created_by,creation_key),
    KEY dataset_draft_page_idx(tenant_id,workspace_id,dataset_id,created_at DESC,id DESC),
    FOREIGN KEY(tenant_id,workspace_id,dataset_id) REFERENCES datasets(tenant_id,workspace_id,id),
    FOREIGN KEY(created_by) REFERENCES users(id),
    CHECK(JSON_TYPE(validation_errors)='ARRAY' AND OCTET_LENGTH(CAST(validation_errors AS CHAR CHARACTER SET utf8mb4))<=8388608),
    CHECK(requested_audience='admin' OR membership_authority IS NOT NULL),
    CHECK((upload_attempt_id IS NULL)=(upload_expires_at IS NULL)),
    CHECK(source_received_at IS NOT NULL OR state IN('uploading','failed','cancelled')),
    CONSTRAINT dataset_drafts_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_drafts_tenant_id_canonical CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_drafts_workspace_id_canonical CHECK(REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_drafts_dataset_id_canonical CHECK(REGEXP_LIKE(dataset_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_drafts_created_by_canonical CHECK(REGEXP_LIKE(created_by,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_drafts_membership_authority_canonical CHECK(membership_authority IS NULL OR REGEXP_LIKE(membership_authority,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_drafts_parent_version_id_canonical CHECK(parent_version_id IS NULL OR REGEXP_LIKE(parent_version_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_drafts_source_object_id_canonical CHECK(REGEXP_LIKE(source_object_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_drafts_upload_attempt_id_canonical CHECK(upload_attempt_id IS NULL OR REGEXP_LIKE(upload_attempt_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_drafts_creation_key_canonical CHECK(REGEXP_LIKE(creation_key,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
