-- SOURCE CANDIDATE ONLY. Active catalog/reference/evolution are unchanged.
CREATE TABLE image_registry_pins (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 asset_id VARCHAR(160) NOT NULL CHECK(CHAR_LENGTH(asset_id)>0),
 source_archive_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(source_archive_sha256,'^[a-f0-9]{64}$','c')),
 source_manifest_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(source_manifest_sha256,'^[a-f0-9]{64}$','c')),
 backend_identity VARCHAR(71) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(backend_identity,'^sha256:[a-f0-9]{64}$','c')),
 state VARCHAR(16) NOT NULL CHECK(state IN('importing','ready','unknown','deleting','deleted','failed')),
 manifest_digest VARCHAR(71) CHARACTER SET ascii COLLATE ascii_bin,
 config_digest VARCHAR(71) CHARACTER SET ascii COLLATE ascii_bin,
 archive_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin, archive_bytes BIGINT,
 inventory JSON, inventory_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin,
 created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 actor_epoch BIGINT NOT NULL CHECK(actor_epoch>=1),
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 revision BIGINT NOT NULL DEFAULT 1 CHECK(revision BETWEEN 1 AND 9007199254740991),
 UNIQUE(tenant_id,workspace_id,id),
 FOREIGN KEY(tenant_id,workspace_id) REFERENCES workspaces(tenant_id,id), FOREIGN KEY(created_by) REFERENCES users(id),
 CHECK((inventory IS NULL)=(manifest_digest IS NULL)), CHECK((inventory IS NULL)=(config_digest IS NULL)),
 CHECK((inventory IS NULL)=(archive_sha256 IS NULL)), CHECK((inventory IS NULL)=(archive_bytes IS NULL)), CHECK((inventory IS NULL)=(inventory_sha256 IS NULL)),
 CHECK(manifest_digest IS NULL OR REGEXP_LIKE(manifest_digest,'^sha256:[a-f0-9]{64}$','c')),
 CHECK(config_digest IS NULL OR REGEXP_LIKE(config_digest,'^sha256:[a-f0-9]{64}$','c')),
 CHECK(archive_sha256 IS NULL OR REGEXP_LIKE(archive_sha256,'^[a-f0-9]{64}$','c')),
 CHECK(inventory_sha256 IS NULL OR REGEXP_LIKE(inventory_sha256,'^[a-f0-9]{64}$','c')),
 CHECK(archive_bytes IS NULL OR archive_bytes>0), CHECK(inventory IS NULL OR JSON_TYPE(inventory)='OBJECT'),
 CHECK(state<>'ready' OR inventory IS NOT NULL),
 CONSTRAINT image_registry_pin_id CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 KEY image_registry_scope(tenant_id,workspace_id,created_at DESC,id DESC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
