CREATE TABLE plugin_versions (
id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
 tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 plugin_id VARCHAR(100) NOT NULL,
 release_version VARCHAR(32) NOT NULL,
 version_major INTEGER NOT NULL CHECK(version_major=1),
 version_minor INTEGER NOT NULL CHECK(version_minor BETWEEN 0 AND 9999),
 version_patch INTEGER NOT NULL CHECK(version_patch BETWEEN 0 AND 9999),
 abi VARCHAR(100) NOT NULL,
 executor VARCHAR(100) NOT NULL,
 capsule MEDIUMBLOB NOT NULL CHECK(OCTET_LENGTH(capsule) BETWEEN 1 AND 1048576),
 capsule_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(capsule_sha256,'^[a-f0-9]{64}$','c')),
 manifest JSON NOT NULL CHECK(JSON_TYPE(manifest)='OBJECT' AND OCTET_LENGTH(CAST(manifest AS CHAR CHARACTER SET utf8mb4))<=16384),
 manifest_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(manifest_sha256,'^[a-f0-9]{64}$','c')),
 key_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(key_id,'^[a-f0-9]{64}$','c')),
 state VARCHAR(16) NOT NULL CHECK(state IN('imported','installed','uninstalled')),
 revision BIGINT NOT NULL DEFAULT 1 CHECK(revision BETWEEN 1 AND 9007199254740991),
 imported_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 installed_at DATETIME(6),
 uninstalled_at DATETIME(6),
 UNIQUE(tenant_id,id),
 UNIQUE(tenant_id,plugin_id,release_version),
 UNIQUE(tenant_id,capsule_sha256),
 KEY plugin_version_page_idx(tenant_id,created_at DESC,id DESC),
 FOREIGN KEY(tenant_id) REFERENCES tenants(id),
 FOREIGN KEY(imported_by) REFERENCES users(id),
 CHECK(state<>'installed' OR installed_at IS NOT NULL),
 CHECK(release_version=CONCAT(version_major,'.',version_minor,'.',version_patch)),
 CONSTRAINT plugin_versions_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT plugin_versions_tenant_id_canonical CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT plugin_versions_imported_by_canonical CHECK(REGEXP_LIKE(imported_by,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
