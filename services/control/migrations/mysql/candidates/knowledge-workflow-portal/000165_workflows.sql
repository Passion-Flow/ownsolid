CREATE TABLE workflows (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
 tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 name VARCHAR(120) NOT NULL CHECK(CHAR_LENGTH(TRIM(name))>0),
 name_key VARCHAR(240) NOT NULL CHECK(CHAR_LENGTH(TRIM(name_key))>0),
 enabled BOOLEAN NOT NULL DEFAULT true CHECK(enabled IN(0,1)),
 execution_authority CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 revision BIGINT NOT NULL DEFAULT 1 CHECK(revision BETWEEN 1 AND 9007199254740991),
 draft_graph JSON NOT NULL CHECK(JSON_TYPE(draft_graph)='OBJECT' AND OCTET_LENGTH(CAST(draft_graph AS CHAR CHARACTER SET utf8mb4))<=1048576),
 draft_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(draft_sha256,'^[a-f0-9]{64}$','c')),
 current_version_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
 created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE(tenant_id,workspace_id,id),
 UNIQUE KEY workflow_name_idx(tenant_id,workspace_id,name_key),
 KEY workflow_page_idx(tenant_id,workspace_id,created_at DESC,id DESC),
 FOREIGN KEY(created_by) REFERENCES users(id),
 FOREIGN KEY(tenant_id,workspace_id) REFERENCES workspaces(tenant_id,id),
 CONSTRAINT workflows_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT workflows_tenant_id_canonical CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT workflows_workspace_id_canonical CHECK(REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT workflows_execution_authority_canonical CHECK(REGEXP_LIKE(execution_authority,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT workflows_current_version_id_canonical CHECK(current_version_id IS NULL OR REGEXP_LIKE(current_version_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT workflows_created_by_canonical CHECK(REGEXP_LIKE(created_by,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
