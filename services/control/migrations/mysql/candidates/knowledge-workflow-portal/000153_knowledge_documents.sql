CREATE TABLE knowledge_documents (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
 tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 base_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 name VARCHAR(255) NOT NULL CHECK(CHAR_LENGTH(name)>0),
 name_key VARCHAR(600) NOT NULL CHECK(CHAR_LENGTH(name_key)>0),
 revision BIGINT NOT NULL DEFAULT 1 CHECK(revision BETWEEN 1 AND 9007199254740991),
 state VARCHAR(12) NOT NULL CHECK(state IN('pending','running','ready','failed','deleted')),
 visible_source_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
 pending_source_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
 current_attempt_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
 created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 deleted_at DATETIME(6),
 delete_reason VARCHAR(500),
 active_name_key VARCHAR(600) GENERATED ALWAYS AS(CASE WHEN deleted_at IS NULL THEN name_key ELSE NULL END) STORED,
 UNIQUE(tenant_id,workspace_id,base_id,id),
 UNIQUE KEY knowledge_document_name_idx(tenant_id,workspace_id,base_id,active_name_key),
 KEY knowledge_document_page_idx(tenant_id,workspace_id,base_id,created_at DESC,id DESC),
 FOREIGN KEY(created_by) REFERENCES users(id),
 FOREIGN KEY(tenant_id,workspace_id,base_id) REFERENCES knowledge_bases(tenant_id,workspace_id,id),
 CHECK((state='deleted' AND deleted_at IS NOT NULL AND delete_reason IS NOT NULL AND CHAR_LENGTH(delete_reason)>0) OR (state<>'deleted' AND deleted_at IS NULL AND delete_reason IS NULL)),
 CHECK(state<>'ready' OR visible_source_id IS NOT NULL),
 CONSTRAINT knowledge_documents_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_documents_tenant_id_canonical CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_documents_workspace_id_canonical CHECK(REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_documents_base_id_canonical CHECK(REGEXP_LIKE(base_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_documents_visible_source_id_canonical CHECK(visible_source_id IS NULL OR REGEXP_LIKE(visible_source_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_documents_pending_source_id_canonical CHECK(pending_source_id IS NULL OR REGEXP_LIKE(pending_source_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_documents_current_attempt_id_canonical CHECK(current_attempt_id IS NULL OR REGEXP_LIKE(current_attempt_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_documents_created_by_canonical CHECK(REGEXP_LIKE(created_by,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
