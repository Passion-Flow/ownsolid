CREATE TRIGGER user_preferences_revision BEFORE UPDATE ON user_preferences FOR EACH ROW
BEGIN
 IF NOT (NEW.user_id <=> OLD.user_id) THEN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='PREFERENCE_OWNER_IMMUTABLE';
 END IF;
 IF NEW.revision<>OLD.revision+1 THEN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='PREFERENCE_REVISION_MUST_ADVANCE';
 END IF;
END;
