CREATE TABLE knowledge_bases (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
 tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 name VARCHAR(100) NOT NULL CHECK(CHAR_LENGTH(name)>0),
 name_key VARCHAR(200) NOT NULL CHECK(CHAR_LENGTH(name_key)>0),
 enabled BOOLEAN NOT NULL DEFAULT true CHECK(enabled IN(0,1)),
 revision BIGINT NOT NULL DEFAULT 1 CHECK(revision BETWEEN 1 AND 9007199254740991),
 initialization_state VARCHAR(12) NOT NULL DEFAULT 'initializing' CHECK(initialization_state IN('initializing','ready')),
 active_generation_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
 building_generation_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
 created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 creation_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 creation_fingerprint VARBINARY(32) NOT NULL CHECK(OCTET_LENGTH(creation_fingerprint)=32),
 UNIQUE(tenant_id,workspace_id,id),
 UNIQUE(tenant_id,workspace_id,created_by,creation_key),
 UNIQUE KEY knowledge_base_name_idx(tenant_id,workspace_id,name_key),
 KEY knowledge_base_page_idx(tenant_id,workspace_id,created_at DESC,id DESC),
 FOREIGN KEY(created_by) REFERENCES users(id),
 FOREIGN KEY(tenant_id,workspace_id) REFERENCES workspaces(tenant_id,id),
 CHECK(building_generation_id IS NULL OR building_generation_id<>active_generation_id),
 CHECK((initialization_state='initializing' AND active_generation_id IS NULL AND building_generation_id IS NULL) OR (initialization_state='ready' AND active_generation_id IS NOT NULL)),
 CONSTRAINT knowledge_bases_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_bases_tenant_id_canonical CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_bases_workspace_id_canonical CHECK(REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_bases_active_generation_id_canonical CHECK(active_generation_id IS NULL OR REGEXP_LIKE(active_generation_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_bases_building_generation_id_canonical CHECK(building_generation_id IS NULL OR REGEXP_LIKE(building_generation_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_bases_created_by_canonical CHECK(REGEXP_LIKE(created_by,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_bases_creation_key_canonical CHECK(REGEXP_LIKE(creation_key,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
