CREATE TABLE knowledge_source_versions (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
 tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 base_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 document_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 source_version BIGINT NOT NULL CHECK(source_version BETWEEN 1 AND 9007199254740991),
 content MEDIUMBLOB NOT NULL,
 size_bytes INTEGER GENERATED ALWAYS AS(OCTET_LENGTH(content)) STORED,
 sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 superseded_at DATETIME(6),
 UNIQUE(tenant_id,workspace_id,base_id,document_id,id),
 UNIQUE(document_id,source_version),
 FOREIGN KEY(created_by) REFERENCES users(id),
 FOREIGN KEY(tenant_id,workspace_id,base_id,document_id) REFERENCES knowledge_documents(tenant_id,workspace_id,base_id,id),
 CHECK(OCTET_LENGTH(content) BETWEEN 1 AND 2097152),
 CHECK(CONVERT(CONVERT(content USING utf8mb4) USING binary)=content AND LOCATE(X'00',content)=0),
 CONSTRAINT knowledge_source_versions_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_source_versions_tenant_id_canonical CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_source_versions_workspace_id_canonical CHECK(REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_source_versions_base_id_canonical CHECK(REGEXP_LIKE(base_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_source_versions_document_id_canonical CHECK(REGEXP_LIKE(document_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_source_versions_created_by_canonical CHECK(REGEXP_LIKE(created_by,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_source_content_digest CHECK(REGEXP_LIKE(sha256,'^[a-f0-9]{64}$','c') AND sha256=SHA2(content,256)),
 CONSTRAINT knowledge_source_superseded_order CHECK(superseded_at IS NULL OR superseded_at>=created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
