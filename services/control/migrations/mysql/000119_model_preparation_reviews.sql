CREATE TABLE model_preparation_reviews (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    preparation_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    attempt_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    artifact_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    report_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(report_sha256,'^[a-f0-9]{64}$','c')),
    expected_revision bigint NOT NULL CHECK(expected_revision BETWEEN 1 AND 9007199254740990),
    decision VARCHAR(16) NOT NULL CHECK(decision IN('approve','reject')),
    model_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    model_name VARCHAR(100) NOT NULL,
    reviewed_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    audience VARCHAR(16) NOT NULL CHECK(audience='admin'),
    reason VARCHAR(500) NOT NULL CHECK(CHAR_LENGTH(TRIM(reason))>0),
    idempotency_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    fingerprint VARBINARY(32) NOT NULL CHECK(OCTET_LENGTH(fingerprint)=32),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT model_review_approval_identity_required CHECK((decision='approve' AND model_id IS NOT NULL AND model_id=artifact_id AND CHAR_LENGTH(TRIM(model_name))>0) OR (decision='reject' AND model_id IS NULL AND model_name='')),
    UNIQUE(tenant_id,workspace_id,id),
    UNIQUE(tenant_id,workspace_id,preparation_id,attempt_id),
    UNIQUE(tenant_id,workspace_id,reviewed_by,idempotency_key),
    FOREIGN KEY(tenant_id,workspace_id,preparation_id,attempt_id,artifact_id) REFERENCES model_preparation_artifacts(tenant_id,workspace_id,preparation_id,attempt_id,id),
    FOREIGN KEY(tenant_id,workspace_id,model_id) REFERENCES model_versions(tenant_id,workspace_id,id),
    FOREIGN KEY(reviewed_by) REFERENCES users(id),
    CONSTRAINT model_preparation_reviews_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_preparation_reviews_tenant_id_canonical CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_preparation_reviews_workspace_id_canonical CHECK(REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_preparation_reviews_preparation_id_canonical CHECK(REGEXP_LIKE(preparation_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_preparation_reviews_attempt_id_canonical CHECK(REGEXP_LIKE(attempt_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_preparation_reviews_artifact_id_canonical CHECK(REGEXP_LIKE(artifact_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_preparation_reviews_model_id_canonical CHECK(model_id IS NULL OR REGEXP_LIKE(model_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_preparation_reviews_reviewed_by_canonical CHECK(REGEXP_LIKE(reviewed_by,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_preparation_reviews_idempotency_key_canonical CHECK(REGEXP_LIKE(idempotency_key,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
