CREATE TABLE deployments (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    node_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    model_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    gpu_uuid VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(gpu_uuid,'^GPU-[a-f0-9-]{36}$','c')),
    desired_state VARCHAR(16) NOT NULL CHECK(desired_state IN('running','stopped','removed')),
    observed_state VARCHAR(16) NOT NULL DEFAULT 'unknown' CHECK(observed_state IN('running','loading','stopped','not_installed','unknown','failed')),
    revision BIGINT NOT NULL CHECK(revision BETWEEN 1 AND 9007199254740991),
    observation JSON,
    observed_at DATETIME(6),
    last_task_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    removed_at DATETIME(6),
    created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    recovery_receipt_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin CHECK(recovery_receipt_sha256 IS NULL OR REGEXP_LIKE(recovery_receipt_sha256,'^[a-f0-9]{64}$','c')),
    retained_node_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin GENERATED ALWAYS AS(CASE WHEN removed_at IS NULL THEN node_id ELSE NULL END) STORED,
    UNIQUE KEY deployment_scope_identity(tenant_id,workspace_id,id),
    UNIQUE KEY deployment_node_identity(tenant_id,workspace_id,node_id,id),
    UNIQUE KEY deployment_one_retained_node_idx(retained_node_id),
    KEY deployment_scope_idx(tenant_id,workspace_id,created_at DESC,id DESC),
    FOREIGN KEY(tenant_id,workspace_id,node_id) REFERENCES managed_nodes(tenant_id,workspace_id,id),
    FOREIGN KEY(tenant_id,workspace_id,model_id) REFERENCES model_versions(tenant_id,workspace_id,id),
    FOREIGN KEY(tenant_id,workspace_id,node_id,last_task_id) REFERENCES node_tasks(tenant_id,workspace_id,node_id,id),
    FOREIGN KEY(created_by) REFERENCES users(id),
    CHECK(observation IS NULL OR JSON_TYPE(observation)='OBJECT' AND OCTET_LENGTH(CAST(observation AS CHAR CHARACTER SET utf8mb4))<=8192),
    CONSTRAINT deployments_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
