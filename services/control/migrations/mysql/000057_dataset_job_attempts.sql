CREATE TABLE dataset_job_attempts (
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    dataset_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    draft_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    attempt_number INT NOT NULL CHECK(attempt_number BETWEEN 1 AND 5),
    state VARCHAR(12) NOT NULL CHECK(state IN('running','succeeded','failed','cancelled','expired')),
    started_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    finished_at DATETIME(6),
    error_code VARCHAR(80),
    memory_enforcement VARCHAR(100),
    PRIMARY KEY(tenant_id,workspace_id,job_id,id),
    UNIQUE KEY dataset_attempt_number(job_id,attempt_number),
    FOREIGN KEY(tenant_id,workspace_id,dataset_id,draft_id,job_id) REFERENCES dataset_jobs(tenant_id,workspace_id,dataset_id,draft_id,id),
    CHECK((state='running' AND finished_at IS NULL) OR (state<>'running' AND finished_at IS NOT NULL)),
    CONSTRAINT dataset_job_attempts_tenant_id_canonical CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_job_attempts_workspace_id_canonical CHECK(REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_job_attempts_dataset_id_canonical CHECK(REGEXP_LIKE(dataset_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_job_attempts_draft_id_canonical CHECK(REGEXP_LIKE(draft_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_job_attempts_job_id_canonical CHECK(REGEXP_LIKE(job_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT dataset_job_attempts_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
