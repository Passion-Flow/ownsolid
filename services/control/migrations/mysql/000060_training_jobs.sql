CREATE TABLE training_jobs (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    node_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    current_node_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    model_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    dataset_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    dataset_version_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    gpu_uuid VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(gpu_uuid,'^GPU-[a-f0-9-]{36}$','c')),
    configuration JSON NOT NULL CHECK(JSON_TYPE(configuration)='OBJECT' AND OCTET_LENGTH(CAST(configuration AS CHAR CHARACTER SET utf8mb4))<=16384),
    configuration_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(configuration_sha256,'^[a-f0-9]{64}$','c')),
    execution_recipe JSON NOT NULL CHECK(JSON_TYPE(execution_recipe)='OBJECT' AND OCTET_LENGTH(CAST(execution_recipe AS CHAR CHARACTER SET utf8mb4))<=32768),
    dataset_manifest_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(dataset_manifest_sha256,'^[a-f0-9]{64}$','c')),
    model_catalog_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(model_catalog_sha256,'^[a-f0-9]{64}$','c')),
    created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    requested_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    requested_audience VARCHAR(8) NOT NULL CHECK(requested_audience IN ('portal','admin')),
    requested_epoch bigint NOT NULL CHECK(requested_epoch>=0),
    membership_authority CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    reason VARCHAR(500) NOT NULL CHECK(CHAR_LENGTH(TRIM(reason))>0),
    creation_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    creation_fingerprint VARBINARY(32) NOT NULL CHECK(OCTET_LENGTH(creation_fingerprint)=32),
    state VARCHAR(24) NOT NULL CHECK(state IN ('queued','preparing','running','cancelling','succeeded','cancelled','failed','recovery_required')),
    wait_code VARCHAR(80),
    next_dispatch_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    revision bigint NOT NULL DEFAULT 1 CHECK(revision BETWEEN 1 AND 9007199254740991),
    attempt_number integer NOT NULL DEFAULT 0 CHECK(attempt_number BETWEEN 0 AND 1000),
    current_attempt_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    accepted_artifact_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    pending_recovery_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    cancel_requested_at DATETIME(6),
    error_code VARCHAR(80),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    finished_at DATETIME(6),
    UNIQUE(tenant_id,workspace_id,id),
    UNIQUE(tenant_id,workspace_id,node_id,id),
    UNIQUE(tenant_id,workspace_id,created_by,creation_key),
    FOREIGN KEY(tenant_id,workspace_id) REFERENCES workspaces(tenant_id,id),
    FOREIGN KEY(tenant_id,workspace_id,node_id) REFERENCES managed_nodes(tenant_id,workspace_id,id),
    FOREIGN KEY(tenant_id,workspace_id,current_node_id) REFERENCES managed_nodes(tenant_id,workspace_id,id),
    FOREIGN KEY(tenant_id,workspace_id,model_id) REFERENCES model_versions(tenant_id,workspace_id,id),
    FOREIGN KEY(tenant_id,workspace_id,dataset_id,dataset_version_id) REFERENCES dataset_versions(tenant_id,workspace_id,dataset_id,id),
    CHECK(requested_audience='admin' OR membership_authority IS NOT NULL),
    KEY training_job_scope_page_idx(tenant_id,workspace_id,created_at DESC,id DESC),
    KEY training_job_queue_idx(state,next_dispatch_at,created_at,id),
    FOREIGN KEY(created_by) REFERENCES users(id),
    FOREIGN KEY(requested_by) REFERENCES users(id),
    CONSTRAINT training_jobs_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_jobs_tenant_id_canonical CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_jobs_workspace_id_canonical CHECK(REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_jobs_node_id_canonical CHECK(REGEXP_LIKE(node_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_jobs_current_node_id_canonical CHECK(REGEXP_LIKE(current_node_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_jobs_model_id_canonical CHECK(REGEXP_LIKE(model_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_jobs_dataset_id_canonical CHECK(REGEXP_LIKE(dataset_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_jobs_dataset_version_id_canonical CHECK(REGEXP_LIKE(dataset_version_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_jobs_created_by_canonical CHECK(REGEXP_LIKE(created_by,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_jobs_requested_by_canonical CHECK(REGEXP_LIKE(requested_by,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_jobs_membership_authority_canonical CHECK(membership_authority IS NULL OR REGEXP_LIKE(membership_authority,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_jobs_creation_key_canonical CHECK(REGEXP_LIKE(creation_key,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_jobs_current_attempt_id_canonical CHECK(current_attempt_id IS NULL OR REGEXP_LIKE(current_attempt_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_jobs_accepted_artifact_id_canonical CHECK(accepted_artifact_id IS NULL OR REGEXP_LIKE(accepted_artifact_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_jobs_pending_recovery_id_canonical CHECK(pending_recovery_id IS NULL OR REGEXP_LIKE(pending_recovery_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
