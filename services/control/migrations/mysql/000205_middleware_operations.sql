CREATE TABLE middleware_operations (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 instance_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 kind VARCHAR(24) NOT NULL CHECK(kind IN('health','backup','isolated_restore','reconcile')),
 state VARCHAR(16) NOT NULL DEFAULT 'queued' CHECK(state IN('queued','running','succeeded','failed','unknown')),
 requested_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 intent_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 intent_fingerprint VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(intent_fingerprint,'^[a-f0-9]{64}$','c')),
 input_json MEDIUMTEXT NOT NULL CHECK(OCTET_LENGTH(input_json)<=65536 AND JSON_VALID(input_json) AND JSON_TYPE(input_json)='OBJECT'),
 actor_json MEDIUMTEXT NOT NULL CHECK(OCTET_LENGTH(actor_json)<=65536 AND JSON_VALID(actor_json) AND JSON_TYPE(actor_json)='OBJECT'),
 instance_version BIGINT NOT NULL CHECK(instance_version BETWEEN 1 AND 9007199254740991),
 profile_fingerprint VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(profile_fingerprint,'^[a-f0-9]{64}$','c')),
 request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 attempt_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
 lease_expires_at DATETIME(6),
 result_json LONGTEXT CHECK(result_json IS NULL OR (OCTET_LENGTH(result_json)<=16777216 AND JSON_VALID(result_json) AND JSON_TYPE(result_json)='OBJECT')),
 result_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin CHECK(result_sha256 IS NULL OR REGEXP_LIKE(result_sha256,'^[a-f0-9]{64}$','c')),
 error_code VARCHAR(96),
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 completed_at DATETIME(6),
 UNIQUE(tenant_id,workspace_id,id),
 UNIQUE(tenant_id,workspace_id,requested_by,intent_key),
 FOREIGN KEY(tenant_id,workspace_id,instance_id) REFERENCES middleware_instances(tenant_id,workspace_id,id),
 FOREIGN KEY(requested_by) REFERENCES users(id),
 CHECK((state='running' AND attempt_id IS NOT NULL AND lease_expires_at IS NOT NULL) OR (state<>'running' AND lease_expires_at IS NULL)),
 CHECK((state='succeeded' AND result_json IS NOT NULL AND result_sha256 IS NOT NULL AND error_code IS NULL AND completed_at IS NOT NULL) OR (state<>'succeeded' AND result_json IS NULL AND result_sha256 IS NULL)),
 CHECK((state IN('failed','unknown') AND error_code IS NOT NULL AND completed_at IS NOT NULL) OR (state NOT IN('failed','unknown') AND error_code IS NULL)),
 CHECK(state<>'queued' OR (attempt_id IS NULL AND completed_at IS NULL)),
 KEY middleware_operations_claim(state,created_at,id),
 KEY middleware_operations_expiry(state,lease_expires_at,id),
 KEY middleware_operations_history(tenant_id,workspace_id,instance_id,id),
 CONSTRAINT middleware_operation_id CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT middleware_operation_tenant_id CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT middleware_operation_workspace_id CHECK(REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT middleware_operation_instance_id CHECK(REGEXP_LIKE(instance_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT middleware_operation_requested_by CHECK(REGEXP_LIKE(requested_by,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT middleware_operation_intent_key CHECK(REGEXP_LIKE(intent_key,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT middleware_operation_request_id CHECK(REGEXP_LIKE(request_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT middleware_operation_attempt_id CHECK(attempt_id IS NULL OR REGEXP_LIKE(attempt_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;