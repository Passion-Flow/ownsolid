CREATE TABLE audit_events (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    occurred_at DATETIME(6) NOT NULL,
    actor_user_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    subject_user_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    audience VARCHAR(16) NOT NULL CHECK(audience IN('portal','admin','operator','system')),
    action VARCHAR(64) NOT NULL,
    outcome VARCHAR(16) NOT NULL CHECK(outcome IN('success','failure','accepted')),
    target_type VARCHAR(48),
    target_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    identifier_digest VARBINARY(32) CHECK(identifier_digest IS NULL OR OCTET_LENGTH(identifier_digest)=32),
    reason VARCHAR(500),
    metadata JSON NOT NULL DEFAULT(JSON_OBJECT()),
    KEY audit_list_idx(occurred_at DESC,id DESC),
    KEY audit_action_idx(action,occurred_at DESC,id DESC),
    FOREIGN KEY(actor_user_id) REFERENCES users(id),
    FOREIGN KEY(subject_user_id) REFERENCES users(id),
    FOREIGN KEY(tenant_id) REFERENCES tenants(id),
    FOREIGN KEY(tenant_id,workspace_id) REFERENCES workspaces(tenant_id,id),
    CHECK(workspace_id IS NULL OR tenant_id IS NOT NULL),
    CHECK(JSON_TYPE(metadata)='OBJECT'),
    CHECK(OCTET_LENGTH(CAST(metadata AS CHAR CHARACTER SET utf8mb4))<=4096),
    CONSTRAINT audit_events_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT audit_request_canonical CHECK(REGEXP_LIKE(request_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT audit_target_canonical CHECK(target_id IS NULL OR REGEXP_LIKE(target_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
