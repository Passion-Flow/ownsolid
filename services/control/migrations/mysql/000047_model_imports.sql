CREATE TABLE model_imports (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    name VARCHAR(100) NOT NULL,
    catalog_digest VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(catalog_digest,'^[a-f0-9]{64}$','c')),
    expected_bytes BIGINT NOT NULL CHECK(expected_bytes BETWEEN 1 AND 2147483648),
    uploaded_bytes BIGINT NOT NULL DEFAULT 0,
    state VARCHAR(16) NOT NULL CHECK(state IN('uploading','queued','verifying','ready','failed','cancelled')),
    error_code VARCHAR(64),
    attempts INT NOT NULL DEFAULT 0 CHECK(attempts BETWEEN 0 AND 3),
    requested_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    requested_epoch BIGINT NOT NULL CHECK(requested_epoch>=0),
    idempotency_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    fingerprint VARBINARY(32) NOT NULL CHECK(OCTET_LENGTH(fingerprint)=32),
    reason VARCHAR(500) NOT NULL,
    model_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    active_workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin GENERATED ALWAYS AS(CASE WHEN state NOT IN('ready','cancelled') THEN workspace_id ELSE NULL END) STORED,
    UNIQUE KEY model_import_scope_identity(tenant_id,workspace_id,id),
    UNIQUE KEY model_import_idempotency(tenant_id,workspace_id,idempotency_key),
    UNIQUE KEY model_import_active_workspace_idx(tenant_id,active_workspace_id),
    KEY model_import_queue_idx(state,created_at,id),
    FOREIGN KEY(tenant_id,workspace_id) REFERENCES workspaces(tenant_id,id),
    FOREIGN KEY(requested_by) REFERENCES users(id),
    FOREIGN KEY(tenant_id,workspace_id,model_id) REFERENCES model_versions(tenant_id,workspace_id,id),
    CHECK(uploaded_bytes>=0 AND uploaded_bytes<=expected_bytes),
    CONSTRAINT model_imports_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_imports_key_canonical CHECK(REGEXP_LIKE(idempotency_key,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
