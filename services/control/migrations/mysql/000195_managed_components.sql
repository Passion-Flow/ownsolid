CREATE TABLE managed_components (
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    node_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    component VARCHAR(32) NOT NULL CHECK(component='node_exporter'),
    version VARCHAR(32) NOT NULL,
    desired_state VARCHAR(16) NOT NULL CHECK(desired_state IN('running','stopped','not_installed')),
    observed_state VARCHAR(16) NOT NULL CHECK(observed_state IN('running','stopped','not_installed','unknown')),
    managed BOOLEAN NOT NULL CHECK(managed IN(0,1)),
    observation JSON NOT NULL CHECK(JSON_TYPE(observation)='OBJECT' AND OCTET_LENGTH(CAST(observation AS CHAR CHARACTER SET utf8mb4))<=8192),
    observed_at DATETIME(6) NOT NULL,
    last_task_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    desired_version VARCHAR(32) NOT NULL DEFAULT '1.12.1' CHECK(desired_version IN('1.12.0','1.12.1')),
    desired_config JSON DEFAULT ('{"log_level":"info","max_scrape_requests":40}') CHECK(desired_config IS NULL OR JSON_TYPE(desired_config)='OBJECT' AND OCTET_LENGTH(CAST(desired_config AS CHAR CHARACTER SET utf8mb4))<=512),
    applied_config JSON CHECK(applied_config IS NULL OR JSON_TYPE(applied_config)='OBJECT' AND OCTET_LENGTH(CAST(applied_config AS CHAR CHARACTER SET utf8mb4))<=512),
    last_verified_at DATETIME(6),
    previous_version VARCHAR(32) CHECK(previous_version IS NULL OR previous_version IN('1.12.0','1.12.1')),
    PRIMARY KEY(node_id,component),
    KEY components_scope_idx(tenant_id,workspace_id,node_id),
    CONSTRAINT components_node_scope_fk FOREIGN KEY(tenant_id,workspace_id,node_id) REFERENCES managed_nodes(tenant_id,workspace_id,id),
    CONSTRAINT components_task_id_fk FOREIGN KEY(last_task_id) REFERENCES node_tasks(id),
    CONSTRAINT components_task_scope_fk FOREIGN KEY(tenant_id,workspace_id,node_id,last_task_id) REFERENCES node_tasks(tenant_id,workspace_id,node_id,id),
    CONSTRAINT managed_components_tenant_id_canonical CHECK(tenant_id IS NULL OR REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT managed_components_workspace_id_canonical CHECK(workspace_id IS NULL OR REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT managed_components_node_id_canonical CHECK(node_id IS NULL OR REGEXP_LIKE(node_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT managed_components_last_task_id_canonical CHECK(last_task_id IS NULL OR REGEXP_LIKE(last_task_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
