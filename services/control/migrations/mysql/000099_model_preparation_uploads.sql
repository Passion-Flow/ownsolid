CREATE TABLE model_preparation_uploads (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    preparation_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    attempt_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
    manifest_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(manifest_sha256,'^[a-f0-9]{64}$','c')),
    manifest JSON NOT NULL CHECK(JSON_TYPE(manifest)='OBJECT' AND OCTET_LENGTH(CAST(manifest AS CHAR CHARACTER SET utf8mb4))<=8388608),
    manifest_bytes LONGBLOB NOT NULL CHECK(OCTET_LENGTH(manifest_bytes) BETWEEN 2 AND 8388608),
    descriptor JSON NOT NULL CHECK(JSON_TYPE(descriptor)='OBJECT' AND OCTET_LENGTH(CAST(descriptor AS CHAR CHARACTER SET utf8mb4))<=32768),
    state VARCHAR(16) NOT NULL DEFAULT 'uploading' CHECK(state IN ('uploading','verifying','accepted','failed')),
    active_chunk_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    active_asset VARCHAR(100),
    active_offset bigint CHECK(active_offset IS NULL OR active_offset BETWEEN 0 AND 2147483648),
    active_expires_at DATETIME(6),
    error_code VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin CHECK(error_code IS NULL OR REGEXP_LIKE(error_code,'^[A-Z][A-Z0-9_]{1,79}$','c')),
    accepted_at DATETIME(6),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UNIQUE(tenant_id,workspace_id,preparation_id,attempt_id,id),
    FOREIGN KEY(tenant_id,workspace_id,preparation_id,attempt_id) REFERENCES model_preparation_attempts(tenant_id,workspace_id,preparation_id,id),
    CHECK((active_chunk_id IS NULL)=(active_asset IS NULL)),
    CHECK((active_chunk_id IS NULL)=(active_offset IS NULL)),
    CHECK((active_chunk_id IS NULL)=(active_expires_at IS NULL)),
    CHECK((state='accepted')=(accepted_at IS NOT NULL)),
    CONSTRAINT model_preparation_uploads_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_preparation_uploads_tenant_id_canonical CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_preparation_uploads_workspace_id_canonical CHECK(REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_preparation_uploads_preparation_id_canonical CHECK(REGEXP_LIKE(preparation_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_preparation_uploads_attempt_id_canonical CHECK(REGEXP_LIKE(attempt_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT model_preparation_uploads_active_chunk_id_canonical CHECK(active_chunk_id IS NULL OR REGEXP_LIKE(active_chunk_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
