CREATE TABLE datasets (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    name VARCHAR(100) NOT NULL CHECK(CHAR_LENGTH(name)>0),
    name_key VARCHAR(200) NOT NULL CHECK(CHAR_LENGTH(name_key)>0),
    origin VARCHAR(2000) NOT NULL CHECK(CHAR_LENGTH(origin)>0),
    license VARCHAR(500) NOT NULL CHECK(CHAR_LENGTH(license)>0),
    rights_asserted BOOLEAN NOT NULL CHECK(rights_asserted=1),
    created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    revision BIGINT NOT NULL DEFAULT 1 CHECK(revision BETWEEN 1 AND 9007199254740991),
    next_version BIGINT NOT NULL DEFAULT 1 CHECK(next_version BETWEEN 1 AND 9007199254740991),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    retired_at DATETIME(6),
    retire_reason VARCHAR(500),
    creation_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    creation_fingerprint VARBINARY(32) NOT NULL CHECK(OCTET_LENGTH(creation_fingerprint)=32),
    active_name_key VARCHAR(200) GENERATED ALWAYS AS(CASE WHEN retired_at IS NULL THEN name_key ELSE NULL END) STORED,
    UNIQUE KEY dataset_scope_identity(tenant_id,workspace_id,id),
    UNIQUE KEY dataset_creation_intent(tenant_id,workspace_id,created_by,creation_key),
    UNIQUE KEY dataset_active_name_idx(tenant_id,workspace_id,active_name_key),
    KEY dataset_workspace_page_idx(tenant_id,workspace_id,created_at DESC,id DESC),
    FOREIGN KEY(tenant_id,workspace_id) REFERENCES workspaces(tenant_id,id),
    FOREIGN KEY(created_by) REFERENCES users(id),
    CHECK((retired_at IS NULL AND retire_reason IS NULL) OR (retired_at IS NOT NULL AND retire_reason IS NOT NULL AND CHAR_LENGTH(retire_reason)>0)),
    CONSTRAINT datasets_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT datasets_tenant_id_canonical CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT datasets_workspace_id_canonical CHECK(REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT datasets_created_by_canonical CHECK(REGEXP_LIKE(created_by,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT datasets_creation_key_canonical CHECK(REGEXP_LIKE(creation_key,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
