CREATE TABLE gateway_instances (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    node_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    name VARCHAR(100) NOT NULL,
    client_origin VARCHAR(2048) NOT NULL CHECK(CHAR_LENGTH(client_origin)>=9),
    control_origin_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(control_origin_sha256,'^[a-f0-9]{64}$','c')),
    credential_hash VARBINARY(32) CHECK(credential_hash IS NULL OR OCTET_LENGTH(credential_hash)=32),
    created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    requested_epoch BIGINT NOT NULL CHECK(requested_epoch>=0),
    idempotency_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    fingerprint VARBINARY(32) NOT NULL CHECK(OCTET_LENGTH(fingerprint)=32),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    revoked_at DATETIME(6),
    revoke_reason VARCHAR(500),
    authority_invalidated_at DATETIME(6),
    active_node_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin GENERATED ALWAYS AS(CASE WHEN revoked_at IS NULL AND authority_invalidated_at IS NULL THEN node_id ELSE NULL END) STORED,
    UNIQUE(tenant_id,workspace_id,id),
    UNIQUE(tenant_id,workspace_id,node_id,id),
    UNIQUE(tenant_id,workspace_id,created_by,idempotency_key),
    UNIQUE KEY gateway_one_active_node_idx(active_node_id),
    FOREIGN KEY(tenant_id,workspace_id,node_id) REFERENCES managed_nodes(tenant_id,workspace_id,id),
    FOREIGN KEY(created_by) REFERENCES users(id),
    CHECK(revoked_at IS NULL OR revoke_reason IS NOT NULL AND CHAR_LENGTH(TRIM(revoke_reason))>0),
    CHECK(credential_hash IS NOT NULL OR authority_invalidated_at IS NOT NULL),
    CONSTRAINT gateway_instances_id_canonical CHECK(id IS NULL OR REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT gateway_instances_tenant_id_canonical CHECK(tenant_id IS NULL OR REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT gateway_instances_workspace_id_canonical CHECK(workspace_id IS NULL OR REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT gateway_instances_node_id_canonical CHECK(node_id IS NULL OR REGEXP_LIKE(node_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT gateway_instances_created_by_canonical CHECK(created_by IS NULL OR REGEXP_LIKE(created_by,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT gateway_instances_idempotency_key_canonical CHECK(idempotency_key IS NULL OR REGEXP_LIKE(idempotency_key,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
