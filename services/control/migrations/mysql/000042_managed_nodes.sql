CREATE TABLE managed_nodes (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    name VARCHAR(100) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK(status IN('active','disabled','removed')),
    version BIGINT NOT NULL DEFAULT 1 CHECK(version BETWEEN 1 AND 9007199254740991),
    credential_hash VARBINARY(32) UNIQUE CHECK(credential_hash IS NULL OR OCTET_LENGTH(credential_hash)=32),
    protocol_version VARCHAR(16) NOT NULL,
    facts JSON NOT NULL,
    last_heartbeat_at DATETIME(6) NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    execution_profile VARCHAR(32) NOT NULL DEFAULT 'read_only' CHECK(execution_profile IN('read_only','systemd_components','systemd_maintenance','docker_inference','docker_ai','docker_model_lifecycle')),
    capabilities JSON NOT NULL DEFAULT (JSON_ARRAY('collect_facts.v1')) CHECK(JSON_TYPE(capabilities)='ARRAY' AND JSON_LENGTH(capabilities)<=11),
    inference_fenced_at DATETIME(6),
    live_name VARCHAR(100) GENERATED ALWAYS AS(CASE WHEN status<>'removed' THEN name ELSE NULL END) STORED,
    UNIQUE KEY nodes_scope_identity(tenant_id,workspace_id,id),
    UNIQUE KEY nodes_live_name_idx(tenant_id,live_name),
    KEY nodes_scope_list_idx(tenant_id,workspace_id,created_at DESC,id DESC),
    FOREIGN KEY(tenant_id,workspace_id) REFERENCES workspaces(tenant_id,id),
    CHECK((status='removed')=(credential_hash IS NULL)),
    CONSTRAINT nodes_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
