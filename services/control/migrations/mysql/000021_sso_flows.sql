CREATE TABLE sso_flows (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    connector_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    connector_revision BIGINT NOT NULL CHECK(connector_revision BETWEEN 1 AND 9007199254740991),
    auth_version BIGINT NOT NULL CHECK(auth_version BETWEEN 1 AND 9007199254740991),
    audience VARCHAR(16) NOT NULL CHECK(audience IN('portal','admin')),
    mode VARCHAR(16) NOT NULL CHECK(mode IN('login','link')),
    state VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK(state IN('pending','claimed','succeeded','failed','expired')),
    state_hash VARBINARY(32) NOT NULL UNIQUE CHECK(OCTET_LENGTH(state_hash)=32),
    browser_hash VARBINARY(32) NOT NULL CHECK(OCTET_LENGTH(browser_hash)=32),
    previous_cookie_hash VARBINARY(32) NOT NULL CHECK(OCTET_LENGTH(previous_cookie_hash)=32),
    previous_session_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    initiating_user_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    initiating_session_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    initiating_epoch BIGINT,
    credential_version BIGINT,
    reason VARCHAR(500),
    verifier_key_id VARCHAR(64),
    verifier_nonce VARBINARY(12),
    verifier_ciphertext VARBINARY(59),
    claim_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    authenticated_user_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    issued_session_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    error_code VARCHAR(80),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    expires_at DATETIME(6) NOT NULL,
    finished_at DATETIME(6),
    UNIQUE KEY sso_flows_tenant_identity(tenant_id,connector_id,id),
    UNIQUE KEY sso_flows_user_identity(tenant_id,connector_id,id,authenticated_user_id),
    KEY sso_flows_expiry_idx(state,expires_at,id),
    KEY sso_flows_connector_idx(tenant_id,connector_id,state),
    FOREIGN KEY(tenant_id,connector_id) REFERENCES sso_connectors(tenant_id,id),
    FOREIGN KEY(initiating_user_id) REFERENCES users(id),
    FOREIGN KEY(authenticated_user_id) REFERENCES users(id),
    CHECK(expires_at>created_at),
    CONSTRAINT sso_flow_link_source CHECK(
      (mode='login' AND initiating_user_id IS NULL AND initiating_session_id IS NULL AND initiating_epoch IS NULL AND credential_version IS NULL AND reason IS NULL)
      OR (mode='link' AND previous_session_id IS NOT NULL AND previous_session_id=initiating_session_id AND initiating_user_id IS NOT NULL AND initiating_session_id IS NOT NULL AND initiating_epoch IS NOT NULL AND credential_version IS NOT NULL AND reason IS NOT NULL AND initiating_epoch BETWEEN 1 AND 9007199254740991 AND credential_version BETWEEN 1 AND 9007199254740991 AND CHAR_LENGTH(TRIM(reason)) BETWEEN 1 AND 500)),
    CONSTRAINT sso_flow_verifier_state CHECK(
      (state='pending' AND verifier_key_id IS NOT NULL AND verifier_nonce IS NOT NULL AND OCTET_LENGTH(verifier_nonce)=12 AND verifier_ciphertext IS NOT NULL AND OCTET_LENGTH(verifier_ciphertext)=59 AND claim_id IS NULL)
      OR (state<>'pending' AND verifier_key_id IS NULL AND verifier_nonce IS NULL AND verifier_ciphertext IS NULL)),
    CHECK(state NOT IN('claimed','succeeded') OR claim_id IS NOT NULL),
    CHECK((state='succeeded')=(authenticated_user_id IS NOT NULL)),
    CHECK(state='succeeded' OR issued_session_id IS NULL),
    CHECK((state IN('succeeded','failed','expired'))=(finished_at IS NOT NULL)),
    CONSTRAINT sso_flow_error_state CHECK(
      (state IN('failed','expired') AND error_code IS NOT NULL AND REGEXP_LIKE(error_code,'^[A-Z][A-Z0-9_]{1,79}$','c') AND NOT REGEXP_LIKE(error_code,'[^A-Z0-9_]','c'))
      OR (state NOT IN('failed','expired') AND error_code IS NULL)),
    CONSTRAINT sso_flows_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CHECK(previous_session_id IS NULL OR REGEXP_LIKE(previous_session_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CHECK(initiating_session_id IS NULL OR REGEXP_LIKE(initiating_session_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CHECK(claim_id IS NULL OR REGEXP_LIKE(claim_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CHECK(issued_session_id IS NULL OR REGEXP_LIKE(issued_session_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
