CREATE TABLE training_uploads (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    attempt_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    kind VARCHAR(16) NOT NULL CHECK(kind IN ('checkpoint','artifact')),
    global_step integer NOT NULL CHECK(global_step BETWEEN 0 AND 1000),
    manifest_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(manifest_sha256,'^[a-f0-9]{64}$','c')),
    manifest JSON NOT NULL CHECK(JSON_TYPE(manifest)='OBJECT' AND OCTET_LENGTH(CAST(manifest AS CHAR CHARACTER SET utf8mb4))<=1048576),
    state VARCHAR(16) NOT NULL CHECK(state IN ('uploading','accepted','failed')),
    manifest_bytes MEDIUMBLOB NOT NULL CHECK(OCTET_LENGTH(manifest_bytes) BETWEEN 2 AND 1048576),
    active_chunk_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
    active_asset VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin CHECK(active_asset IS NULL OR REGEXP_LIKE(active_asset,'^[A-Za-z0-9_.-]{1,100}$','c')),
    active_offset bigint CHECK(active_offset IS NULL OR active_offset>=0 AND active_offset%8388608=0),
    active_expires_at DATETIME(6),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UNIQUE(tenant_id,workspace_id,job_id,attempt_id,id),
    UNIQUE(attempt_id,kind,global_step),
    FOREIGN KEY(tenant_id,workspace_id,job_id,attempt_id) REFERENCES training_attempts(tenant_id,workspace_id,job_id,id),
    CHECK(((active_chunk_id IS NOT NULL)+(active_asset IS NOT NULL)+(active_offset IS NOT NULL)+(active_expires_at IS NOT NULL)) IN (0,4)),
    CONSTRAINT training_uploads_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_uploads_tenant_id_canonical CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_uploads_workspace_id_canonical CHECK(REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_uploads_job_id_canonical CHECK(REGEXP_LIKE(job_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_uploads_attempt_id_canonical CHECK(REGEXP_LIKE(attempt_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT training_uploads_active_chunk_id_canonical CHECK(active_chunk_id IS NULL OR REGEXP_LIKE(active_chunk_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
