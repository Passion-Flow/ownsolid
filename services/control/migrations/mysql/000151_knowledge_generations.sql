CREATE TABLE knowledge_generations (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
 tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 base_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 catalog_sha256 VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK(REGEXP_LIKE(catalog_sha256,'^[a-f0-9]{64}$','c')),
 dimension INTEGER NOT NULL CHECK(dimension=384),
 chunk_tokens INTEGER NOT NULL CHECK(chunk_tokens BETWEEN 8 AND 254),
 overlap_tokens INTEGER NOT NULL,
 state VARCHAR(12) NOT NULL CHECK(state IN('building','active','failed','retired')),
 requested_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 requested_audience VARCHAR(8) NOT NULL CHECK(requested_audience IN('portal','admin')),
 requested_epoch BIGINT NOT NULL CHECK(requested_epoch>=0),
 membership_authority CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
 expected_documents INTEGER NOT NULL CHECK(expected_documents BETWEEN 0 AND 1000),
 error_code VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin CHECK(error_code IS NULL OR REGEXP_LIKE(error_code,'^[A-Z][A-Z0-9_]{1,79}$','c')),
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 activated_at DATETIME(6),
 finished_at DATETIME(6),
 active_base_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin GENERATED ALWAYS AS(CASE WHEN state='active' THEN base_id ELSE NULL END) STORED,
 building_base_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin GENERATED ALWAYS AS(CASE WHEN state='building' THEN base_id ELSE NULL END) STORED,
 UNIQUE(tenant_id,workspace_id,base_id,id),
 UNIQUE KEY knowledge_one_active_generation_idx(tenant_id,workspace_id,active_base_id),
 UNIQUE KEY knowledge_one_building_generation_idx(tenant_id,workspace_id,building_base_id),
 FOREIGN KEY(requested_by) REFERENCES users(id),
 FOREIGN KEY(tenant_id,workspace_id,base_id) REFERENCES knowledge_bases(tenant_id,workspace_id,id),
 CHECK(requested_audience='admin' OR membership_authority IS NOT NULL),
 CHECK(state<>'active' OR activated_at IS NOT NULL),
 CONSTRAINT knowledge_generations_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_generations_tenant_id_canonical CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_generations_workspace_id_canonical CHECK(REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_generations_base_id_canonical CHECK(REGEXP_LIKE(base_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_generations_requested_by_canonical CHECK(REGEXP_LIKE(requested_by,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_generations_membership_authority_canonical CHECK(membership_authority IS NULL OR REGEXP_LIKE(membership_authority,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT knowledge_generations_overlap_bounds CHECK(overlap_tokens>=0 AND overlap_tokens<chunk_tokens)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
