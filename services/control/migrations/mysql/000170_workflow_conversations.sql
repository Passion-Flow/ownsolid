CREATE TABLE workflow_conversations (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
 tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 workflow_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 version_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 owner_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 revision BIGINT NOT NULL DEFAULT 1 CHECK(revision BETWEEN 1 AND 9007199254740991),
 turn_count INTEGER NOT NULL DEFAULT 0 CHECK(turn_count BETWEEN 0 AND 10000),
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 deleted_at DATETIME(6),
 UNIQUE(tenant_id,workspace_id,workflow_id,id),
 UNIQUE(tenant_id,workspace_id,workflow_id,id,owner_id,version_id),
 KEY workflow_conversation_page_idx(tenant_id,workspace_id,owner_id,deleted_at,created_at DESC,id DESC),
 KEY application_conversation_updated_idx(tenant_id,workspace_id,owner_id,deleted_at,updated_at DESC,id DESC),
 FOREIGN KEY(owner_id) REFERENCES users(id),
 FOREIGN KEY(tenant_id,workspace_id,workflow_id,version_id) REFERENCES workflow_versions(tenant_id,workspace_id,workflow_id,id),
 CONSTRAINT workflow_conversations_id_canonical CHECK(REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT workflow_conversations_tenant_id_canonical CHECK(REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT workflow_conversations_workspace_id_canonical CHECK(REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT workflow_conversations_workflow_id_canonical CHECK(REGEXP_LIKE(workflow_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT workflow_conversations_version_id_canonical CHECK(REGEXP_LIKE(version_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
 CONSTRAINT workflow_conversations_owner_id_canonical CHECK(REGEXP_LIKE(owner_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
