CREATE TABLE api_keys (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    alias_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    label VARCHAR(100) NOT NULL,
    secret_hash VARBINARY(32) NOT NULL CHECK(OCTET_LENGTH(secret_hash)=32),
    created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    requested_epoch BIGINT NOT NULL CHECK(requested_epoch>=0),
    membership_authority CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    idempotency_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    fingerprint VARBINARY(32) NOT NULL CHECK(OCTET_LENGTH(fingerprint)=32),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    expires_at DATETIME(6) NOT NULL,
    last_used_at DATETIME(6),
    revoked_at DATETIME(6),
    revoke_reason VARCHAR(500),
    UNIQUE(tenant_id,workspace_id,id),
    UNIQUE(tenant_id,workspace_id,created_by,idempotency_key),
    KEY api_key_owner_idx(tenant_id,workspace_id,created_by,created_at DESC,id DESC),
    CONSTRAINT api_key_creator_fk FOREIGN KEY(created_by) REFERENCES users(id),
    CONSTRAINT api_key_alias_scope_fk FOREIGN KEY(tenant_id,workspace_id,alias_id) REFERENCES model_aliases(tenant_id,workspace_id,id),
    CONSTRAINT api_key_expiry_order CHECK(expires_at>created_at),
    CONSTRAINT api_key_revocation_reason CHECK(revoked_at IS NULL OR (revoke_reason IS NOT NULL AND CHAR_LENGTH(revoke_reason)>0)),
    CONSTRAINT api_keys_id_canonical CHECK(id IS NULL OR REGEXP_LIKE(id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT api_keys_tenant_id_canonical CHECK(tenant_id IS NULL OR REGEXP_LIKE(tenant_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT api_keys_workspace_id_canonical CHECK(workspace_id IS NULL OR REGEXP_LIKE(workspace_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT api_keys_alias_id_canonical CHECK(alias_id IS NULL OR REGEXP_LIKE(alias_id,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT api_keys_created_by_canonical CHECK(created_by IS NULL OR REGEXP_LIKE(created_by,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT api_keys_membership_authority_canonical CHECK(membership_authority IS NULL OR REGEXP_LIKE(membership_authority,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c')),
    CONSTRAINT api_keys_idempotency_key_canonical CHECK(idempotency_key IS NULL OR REGEXP_LIKE(idempotency_key,'^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
