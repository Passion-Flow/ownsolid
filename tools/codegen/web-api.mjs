// Generates the web workspace's TypeScript contracts from api/openapi/v1/<domain>/openapi.json
// into web/packages/api/src/gen. Run from anywhere:
//
//   node tools/codegen/web-api.mjs          write the files
//   node tools/codegen/web-api.mjs --check  fail when they differ from the contracts
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const contracts = join(root, 'api', 'openapi', 'v1');
const output = join(root, 'web', 'packages', 'api', 'src', 'gen');

// The generator is a dependency of the package it writes into.
const require = createRequire(join(root, 'web', 'packages', 'api', 'package.json'));
const { default: openapiTS, astToString } = require('openapi-typescript');

const banner = (source) =>
  `// Generated by tools/codegen/web-api.mjs from ${source}. Do not edit.\n// Change the contract, then run \`make generate\`.\n\n`;

const camelCase = (name) => name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());

async function generate() {
  const files = new Map();
  const domains = readdirSync(contracts, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    // Some domains publish only problem or policy schemas.
    .filter((name) => existsSync(join(contracts, name, 'openapi.json')))
    .sort();
  for (const domain of domains) {
    const source = join(contracts, domain, 'openapi.json');
    const ast = await openapiTS(pathToFileURL(source));
    files.set(`${domain}.ts`, banner(`api/openapi/v1/${domain}/openapi.json`) + astToString(ast));
  }
  const index = domains
    .map((domain) => `export type * as ${camelCase(domain)}Contract from './${domain}.ts';`)
    .join('\n');
  files.set('index.ts', `${banner('api/openapi/v1')}${index}\n`);
  return files;
}

function current() {
  try {
    return new Map(
      readdirSync(output).map((name) => [name, readFileSync(join(output, name), 'utf8')]),
    );
  } catch {
    return new Map();
  }
}

const files = await generate();

if (process.argv.includes('--check')) {
  const existing = current();
  const stale = [...new Set([...files.keys(), ...existing.keys()])].filter(
    (name) => files.get(name) !== existing.get(name),
  );
  if (stale.length > 0) {
    console.error(`generated API types are out of date: ${stale.join(', ')}`);
    console.error('run `make generate` and commit the result');
    process.exit(1);
  }
  console.log(`generated API types match ${files.size - 1} contracts`);
} else {
  rmSync(output, { recursive: true, force: true });
  mkdirSync(output, { recursive: true });
  for (const [name, content] of files) writeFileSync(join(output, name), content);
  console.log(`wrote ${files.size} files to web/packages/api/src/gen`);
}
